// Run only against a native-created disposable zone. Never touches RiseSharedTabs.
import {readFileSync,writeFileSync} from 'node:fs';
import assert from 'node:assert/strict';
import {CloudKit} from '../../src/cloudkit.js';
import {DEFAULT_CONFIG,API_TOKENS} from '../../src/config.js';
import {decodePayload,encodePayload,Ledger,uuid} from '../../src/ledger.js';
const file=process.argv[2],data=JSON.parse(readFileSync(file,'utf8'));
assert.match(data.zone,/^RiseWebAudit-[0-9A-F-]{36}$/);assert.ok(data.token,'Complete Apple sign-in first.');
const auth={token:data.token};
const environment=process.argv[3]??DEFAULT_CONFIG.environment;
const ck=new CloudKit({apiToken:API_TOKENS[environment],environment,zoneName:data.zone},auth,async()=>{data.token=auth.token;writeFileSync(file,JSON.stringify(data),{mode:0o600});});
const user=await ck.user();assert.ok(user.userRecordName);console.log('PASS: authenticated CloudKit Web Services access');
const first=await ck.changes();assert.equal(first.records.length,1);
const native=first.records[0];const r=decodePayload(native.fields.payload.value);assert.equal(r.tab.title,'Native → web 🌅');
console.log('PASS: web client decodes native JSON Bytes, Unicode, UUID and versions');
const ledger=new Ledger();ledger.merge(r);ledger.observedTabs=ledger.tabs;ledger.capture([{...r.tab,title:'Web → native 🌅'}]);
let modified=ledger.records[r.tab.id];
const op=(value,tag)=>({operationType:tag?'update':'create',record:{recordName:value.tab.id,recordType:'RiseTab',...(tag?{recordChangeTag:tag}:{}),fields:{payload:{type:'BYTES',value:encodePayload(value)}}}});
const saved=(await ck.modify([op(modified,native.recordChangeTag)]))[0];assert.equal(saved.serverErrorCode,undefined);
console.log('PASS: versioned web update writes the native payload schema');
const conflict=(await ck.modify([op(modified,native.recordChangeTag)]))[0];assert.equal(conflict.serverErrorCode,'CONFLICT');
const looked=(await ck.lookup([r.tab.id]))[0];assert.equal(looked.recordChangeTag,saved.recordChangeTag);
console.log('PASS: stale tags conflict and records/lookup returns the current version');
ledger.close(r.tab.id);modified=ledger.records[r.tab.id];
const closed=(await ck.modify([op(modified,saved.recordChangeTag)]))[0];assert.equal(closed.serverErrorCode,undefined);
const added={...modified,tab:{id:uuid(),url:'https://example.com/web-created',title:'Web insert'},closedAt:undefined};
const created=(await ck.modify([op(added)]))[0];assert.equal(created.serverErrorCode,undefined);
const changes=await ck.changes(first.syncToken);assert.ok(changes.records.some(x=>x.recordName===r.tab.id&&decodePayload(x.fields.payload.value).closedAt));
console.log('PASS: incremental changes include the closure tombstone and web-created tab');
console.log('Web audit passed. Run native verify to check the result and delete the disposable zone.');
